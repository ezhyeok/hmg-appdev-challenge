def _load_sim():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'docs', 'plan', 'data',
                        'effect_sim.json')
    try:
        with open(path, encoding='utf-8') as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


_SIM = _load_sim()
MAIN = 'child7_holiday_sigma0.3'
FREE = 'child7_free_sigma0.3'


def _cond(key):
    for c in (_SIM or {}).get('conditions', []):
        if c.get('key') == key:
            return c
    return None


def _pct(c, policy, metric='crisisOver30MinShare'):
    return round(100 * c['policies'][policy][metric]['value'])


def _mean(c, policy, metric):
    return c['policies'][policy][metric]['mean']


def _prompts(c, policy):
    p = c['policies'][policy].get('enginePromptsPerTrip') or {}
    return p.get('lastChance', 0) + p.get('restSuggestion', 0)


def _hm(minutes):
    m = int(round(minutes))
    return "%d시간 %d분" % (m // 60, m % 60) if m % 60 else "%d시간" % (m // 60)


def _sim_numbers():
    main, free = _cond(MAIN), _cond(FREE)
    if not main:
        return None
    s7_min = _mean(main, 'shimpyoP07', 'tripMin')
    return {
        'trips': main['trips'],
        'now': _pct(main, 'nowLike'), 'e2': _pct(main, 'every2h'),
        's7': _pct(main, 'shimpyoP07'), 's10': _pct(main, 'shimpyoP10'),
        'dStops': _mean(main, 'shimpyoP07', 'stopsPerTrip') - _mean(main, 'every2h', 'stopsPerTrip'),
        'dMin': s7_min - _mean(main, 'every2h', 'tripMin'),
        'e2Stops': _mean(main, 'every2h', 'stopsPerTrip') - _mean(main, 'nowLike', 'stopsPerTrip'),
        'long_e2': _pct(main, 'every2h', 'stretchOver2h30Share'),
        'long_s7': _pct(main, 'shimpyoP07', 'stretchOver2h30Share'),
        'long_s10': _pct(main, 'shimpyoP10', 'stretchOver2h30Share'),
        'prompts': _prompts(main, 'shimpyoP07'),
        'promptsPerHour': _prompts(main, 'shimpyoP07') / (s7_min / 60.0),
        'tripHM': _hm(s7_min),
        'freeZero': free is not None and all(
            free['policies'][p]['crisisOver30MinShare']['value'] == 0 for p in free['policies']),
    }


SIM = _sim_numbers()


