# Numbers are read from the file so the text always matches the figure.

def _load_sim():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'docs', 'plan', 'data',
                        'effect_sim.json')
    try:
        with open(path, encoding='utf-8') as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


_SIM = _load_sim()


def _cond(key):
    for c in (_SIM or {}).get('conditions', []):
        if c.get('key') == key:
            return c
    return None


def _pct(c, policy, metric='crisisOver30MinShare'):
    return round(100 * c['policies'][policy][metric]['value'])


def _mean(c, policy, metric):
    return c['policies'][policy][metric]['mean']


def _sim_numbers():
    main = _cond('child7_holiday_sigma0.3')
    free = _cond('child7_free_sigma0.3')
    if not main:
        return None
    n = {
        'trips': main['trips'],
        'now': _pct(main, 'nowLike'), 'e2': _pct(main, 'every2h'),
        's7': _pct(main, 'shimpyoP07'), 's10': _pct(main, 'shimpyoP10'),
        'dStops': _mean(main, 'shimpyoP07', 'stopsPerTrip') - _mean(main, 'every2h', 'stopsPerTrip'),
        'dMin': _mean(main, 'shimpyoP07', 'tripMin') - _mean(main, 'every2h', 'tripMin'),
        'e2Stops': _mean(main, 'every2h', 'stopsPerTrip') - _mean(main, 'nowLike', 'stopsPerTrip'),
        'long_now': _pct(main, 'nowLike', 'stretchOver2h30Share'),
        'long_s7': _pct(main, 'shimpyoP07', 'stretchOver2h30Share'),
        'freeZero': free is not None and all(
            free['policies'][p]['crisisOver30MinShare']['value'] == 0 for p in free['policies']),
    }
    others = []
    for key, label in (('child4', '4살 아이'), ('elderly', '어르신'), ('oabDriver', '과민성 방광 운전자'),
                       ('adults', '어른 2명')):
        c = _cond(key + '_holiday_sigma0.3')
        if c:
            others.append('%s %d%%→%d%%' % (label, _pct(c, 'nowLike'), _pct(c, 'shimpyoP07')))
    n['others'] = ', '.join(others)
    return n


