def sim_table():
    main = _cond(MAIN)
    if not main:
        return P("[[시뮬레이션 표]]")
    rows = []
    for key, label in SIM_POLICIES:
        n = _prompts(main, key)
        rows.append([label,
                     "%d%%" % _pct(main, key),
                     "%.1f회" % _mean(main, key, 'stopsPerTrip'),
                     "%d분" % round(_mean(main, key, 'tripMin')),
                     "%d%%%s" % (_pct(main, key, 'stretchOver2h30Share'), "¹" if key == 'nowLike' else ""),
                     ("%.1f회" % n) if n > 0 else "—"])
